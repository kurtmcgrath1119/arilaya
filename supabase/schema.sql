create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  name text not null default '',
  picture text not null default '',
  role text check (role in ('buyer', 'seller', 'admin')),
  phone text not null default '',
  street text not null default '',
  barangay text not null default '',
  city text not null default '',
  province text not null default '',
  google_sub text,
  legacy_id integer,
  created_at timestamptz not null default now()
);

create unique index if not exists profiles_email_unique on public.profiles (lower(email));
create unique index if not exists profiles_google_sub_unique on public.profiles (google_sub) where google_sub is not null;
create unique index if not exists profiles_legacy_id_unique on public.profiles (legacy_id) where legacy_id is not null;

create table if not exists public.lots (
  id integer generated by default as identity primary key,
  title text not null,
  barangay text not null,
  address text not null default '',
  nearest_road text not null default '',
  landmark text not null default '',
  price double precision not null check (price >= 0),
  area_sqm double precision not null check (area_sqm > 0),
  land_type text not null default 'residential' check (land_type in ('residential', 'agricultural', 'commercial', 'industrial')),
  status text not null default 'available' check (status in ('available', 'reserved', 'sold')),
  seller_name text not null default '',
  seller_phone text not null default '',
  description text not null default '',
  boundary jsonb not null,
  center_lat double precision not null,
  center_lng double precision not null,
  owner_id uuid references public.profiles(id) on delete set null,
  approval text not null default 'approved' check (approval in ('pending', 'approved', 'rejected')),
  updated_at timestamptz not null default now()
);

create index if not exists lots_public_idx on public.lots (approval, id desc);
create index if not exists lots_owner_idx on public.lots (owner_id, id desc);
create index if not exists lots_location_idx on public.lots (center_lat, center_lng);

create table if not exists public.landmarks (
  id integer generated by default as identity primary key,
  name text not null,
  category text not null default '',
  lat double precision not null,
  lng double precision not null
);

create table if not exists public.feedback (
  id integer generated by default as identity primary key,
  role text not null default 'buyer' check (role in ('buyer', 'seller', 'stakeholder')),
  functionality integer check (functionality between 1 and 5),
  usability integer check (usability between 1 and 5),
  reliability integer check (reliability between 1 and 5),
  satisfaction integer check (satisfaction between 1 and 5),
  comment text not null default '',
  created_at timestamptz not null default now()
