create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  metadata jsonb := coalesce(new.raw_user_meta_data, '{}'::jsonb);
  selected_role text := metadata->>'role';
  profile_name text;
begin
  selected_role := null;

  profile_name := nullif(trim(concat_ws(' ', metadata->>'first_name', metadata->>'last_name')), '');
  if profile_name is null then
    profile_name := nullif(metadata->>'full_name', '');
  end if;
  if profile_name is null then
    profile_name := nullif(metadata->>'name', '');
  end if;
  if profile_name is null then
    profile_name := split_part(coalesce(new.email, ''), '@', 1);
  end if;

  insert into public.profiles (
    id, email, name, picture, role, phone, street, barangay, city, province, google_sub
  ) values (
    new.id,
    coalesce(new.email, ''),
    profile_name,
    coalesce(nullif(metadata->>'picture', ''), nullif(metadata->>'avatar_url', ''), ''),
    selected_role,
    coalesce(metadata->>'phone', ''),
    coalesce(metadata->>'street', ''),
    coalesce(metadata->>'barangay', ''),
    coalesce(metadata->>'city', ''),
    coalesce(metadata->>'province', ''),
    case when new.raw_app_meta_data->>'provider' = 'google' then nullif(metadata->>'sub', '') end
  ) on conflict (id) do nothing;

  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

create or replace function public.choose_role(p_role text)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  existing_role text;
begin
  if current_user_id is null then
    raise exception 'Authentication required';
  end if;
  if p_role not in ('buyer', 'seller') then
    raise exception 'Choose buyer or seller';
  end if;

  select role into existing_role from public.profiles where id = current_user_id;
  if not found then
    raise exception 'Profile not found';
  end if;

  if existing_role is null then
    update public.profiles set role = p_role where id = current_user_id;
    return p_role;
  end if;

  return existing_role;
end;
$$;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.profiles
    where id = auth.uid() and role = 'admin'
  );
$$;

revoke all on function public.choose_role(text) from public, anon;
revoke all on function public.is_admin() from public, anon;
grant execute on function public.choose_role(text) to authenticated;
grant execute on function public.is_admin() to authenticated;

